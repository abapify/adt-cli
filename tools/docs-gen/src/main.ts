#!/usr/bin/env bun
/**
 * docs-gen — regenerates the CLI and MCP reference pages of the website
 * from code (Commander command tree + MCP tool registry).
 *
 *   bunx nx run docs-gen:docs:gen     # write pages
 *   bunx nx run docs-gen:docs:check   # fail if pages are out of date (CI)
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { generateCliPages } from './cli-reference';
import { generateMcpPages } from './mcp-reference';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url)).replace(
  /[/\\]$/,
  '',
);
const DOCS = join(ROOT, 'website/docs');
const SIDEBAR = join(ROOT, 'website/sidebars.generated.ts');
/** Directories whose every `.md` file is owned by this generator. */
const OWNED_DIRS = ['cli/reference', 'mcp/tools'];

const check = process.argv.includes('--check');

async function format(file: string, content: string): Promise<string> {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(content, { ...config, filepath: file });
}

function read(file: string): string | undefined {
  return existsSync(file) ? readFileSync(file, 'utf8') : undefined;
}

const outputs = new Map<string, string>();

const cliPages = await generateCliPages();
for (const page of cliPages)
  outputs.set(join(DOCS, `${page.id}.md`), page.content);

const mcpPages = generateMcpPages(ROOT);
for (const page of mcpPages) {
  const file = join(DOCS, `${page.id}.md`);
  outputs.set(file, page.render(read(file)));
}

const ids = (list: { id: string }[]) =>
  list.map((p) => `  '${p.id}',`).join('\n');
outputs.set(
  SIDEBAR,
  [
    '// Generated by `bunx nx run docs-gen:docs:gen` — do not edit by hand.',
    `export const cliReferenceDocs = [\n${ids(cliPages.filter((p) => !p.id.endsWith('/index')))}\n];`,
    `export const mcpToolDocs = [\n${ids(mcpPages)}\n];`,
    '',
  ].join('\n'),
);

const changed: string[] = [];
const formatted = await Promise.all(
  [...outputs].map(
    async ([file, raw]) => [file, await format(file, raw)] as const,
  ),
);
for (const [file, content] of formatted) {
  if (read(file) === content) continue;
  changed.push(relative(ROOT, file));
  if (!check) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}

for (const dir of OWNED_DIRS) {
  const abs = join(DOCS, dir);
  if (!existsSync(abs)) continue;
  for (const name of readdirSync(abs)) {
    const file = join(abs, name);
    if (!name.endsWith('.md') || outputs.has(file)) continue;
    changed.push(`${relative(ROOT, file)} (stale)`);
    if (!check) rmSync(file);
  }
}

if (changed.length === 0) {
  console.log(`docs-gen: ${outputs.size} generated files are up to date.`);
} else if (check) {
  console.error(
    `docs-gen: ${changed.length} generated file(s) are out of date:\n` +
      changed.map((f) => `  - ${f}`).join('\n') +
      '\n\nRun `bunx nx run docs-gen:docs:gen` and commit the result.',
  );
  process.exit(1);
} else {
  console.log(
    `docs-gen: updated ${changed.length} file(s):\n` +
      changed.map((f) => `  - ${f}`).join('\n'),
  );
}
