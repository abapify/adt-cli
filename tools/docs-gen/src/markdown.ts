function escapeAngles(text: string): string {
  return text.replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

/** Escape text for use in MDX prose (keeps line breaks). */
export function escapeText(text: string): string {
  return escapeAngles(text.replace(/[\\{}]/g, String.raw`\$&`));
}

/** Escape text for use in a single Markdown table cell. */
export function escapeCell(text: string): string {
  return escapeAngles(text.replace(/[\\{}|]/g, String.raw`\$&`)).replace(
    /(?<![^\S\n])[^\S\n]*(?:\n[^\S\n]*)+/g,
    ' ',
  );
}

function codeSpan(text: string): string {
  const fence = '`'.repeat(
    Math.max(1, ...(text.match(/`+/g) ?? []).map((run) => run.length + 1)),
  );
  return `${fence}${text}${fence}`;
}

/**
 * Inline code that is safe inside a table cell. A `|` cannot be escaped
 * inside a code span without also mangling backslashes, so each side of
 * a `|` gets its own span: `"a" | "b"` becomes `"a"` \| `"b"`.
 */
export function code(text: string): string {
  return text
    .split('|')
    .map((part) => part.trim())
    .map(codeSpan)
    .join(String.raw` \| `);
}

export function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

export function frontmatter(fields: Record<string, string>): string {
  const lines = Object.entries(fields).map(
    ([k, v]) => `${k}: ${JSON.stringify(v)}`,
  );
  return `---\n${lines.join('\n')}\n---`;
}

/** First sentence of a description, for frontmatter `description`. */
export function summary(text: string | undefined): string {
  const line = (text ?? '').trim().split(/\r?\n/)[0] ?? '';
  // Sentence end: [.!?] followed by whitespace/EOL, but never inside a
  // letter-dot-letter abbreviation like "e.g." or "i.e.".
  let idx = 0;
  for (;;) {
    const hit = line.slice(idx).search(/[.!?](?=\s|$)/);
    if (hit === -1) return line.trim();
    const pos = idx + hit;
    if (!/[a-zA-Z]\.[a-zA-Z]$/.test(line.slice(0, pos))) {
      return line.slice(0, pos + 1).trim();
    }
    idx = pos + 1;
  }
}

export function generatedNote(source: string): string {
  return `<!-- Generated by \`bunx nx run docs-gen:docs:gen\` from ${source}. Do not edit by hand. -->`;
}
