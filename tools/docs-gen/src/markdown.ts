/** Escape text for use in MDX prose (keeps line breaks). */
export function escapeText(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}');
}

/** Escape text for use in a single Markdown table cell. */
export function escapeCell(text: string): string {
  return escapeText(text)
    .replace(/\|/g, '\\|')
    .replace(/\s*\r?\n\s*/g, ' ');
}

/** Inline code span that is safe inside a table cell. */
export function code(text: string): string {
  const fence = text.includes('`') ? '``' : '`';
  return `${fence}${text.replace(/\|/g, '\\|')}${fence}`;
}

export function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

export function frontmatter(fields: Record<string, string>): string {
  const lines = Object.entries(fields).map(
    ([k, v]) => `${k}: ${JSON.stringify(v)}`,
  );
  return `---\n${lines.join('\n')}\n---`;
}

/** First sentence of a description, for frontmatter `description`. */
export function summary(text: string | undefined): string {
  const line = (text ?? '').trim().split(/\r?\n/)[0] ?? '';
  const sentence = line.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? line;
  return sentence.trim();
}

export function generatedNote(source: string): string {
  return `<!-- Generated by \`bunx nx run docs-gen:docs:gen\` from ${source}. Do not edit by hand. -->`;
}
